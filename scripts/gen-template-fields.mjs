#!/usr/bin/env node
/**
 * Regenerates components/editor/templateFieldPaths.generated.ts — the content
 * paths each template actually binds.
 *
 * WHY THIS EXISTS. The Content panel offered every field in the schema on every
 * template. An admin editing Villa Marindu got Rating, Price, Price unit,
 * Feature chips and Image on each services row — but that design's inclusion
 * ledger is a numeral, a name, a description and one tag, so six of the nine
 * inputs wrote to storage and changed nothing on the page. Filtering the GROUPS
 * by section (templateSectionOrder) was only half the job: a section a template
 * renders can still draw a fraction of the fields the schema declares for it.
 *
 * The truth is in the components. Every editable string is bound with
 * data-field / data-image-field / data-href-field, so the set of paths a
 * template can actually show is readable straight off its wrapper and the
 * section components it imports.
 *
 * IT FAILS OPEN, ON PURPOSE. The scan matches any path-shaped token with a known
 * content root anywhere in a file — including inside comments, and including
 * paths assembled by a helper such as `lineField(i)`. A path mentioned but not
 * bound therefore keeps its input visible, which is the harmless direction: a
 * spare field an admin can ignore beats a missing one they need. A template that
 * cannot be scanned at all is left unfiltered entirely.
 *
 * Usage:
 *   node scripts/gen-template-fields.mjs           # rewrite the generated file
 *   node scripts/gen-template-fields.mjs --check   # fail if it is stale (CI)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const COMPONENTS = path.join(ROOT, "astro-site-template/src/components");
const OUT = path.join(ROOT, "components/editor/templateFieldPaths.generated.ts");

/**
 * The content roots the schema declares. A token only counts as a path if it
 * starts with one of these, which keeps CSS classes and JS identifiers out.
 */
// Exported so scripts/check-template-field-roots.mjs validates against the SAME
// list rather than a copy of it. Two lists that can drift is the bug this
// whole directory keeps re-learning.
export const ROOTS = [
    "hero", "about", "services", "why", "how", "testimonials", "gallery", "faq",
    "area", "credentials", "location", "ctaBand", "footer", "trust", "marquee",
    "navbar_links", "business_name", "tagline", "navCtaText", "navCtaHref",
    // Declared editable by genericContentSchema (contact.phone / .address /
    // .email) and bound by 63 header components, but missing here — so the
    // scan never collected it and the Content panel filtered the shop's own
    // phone number out of every template. Found by
    // scripts/check-template-field-roots.mjs.
    "contact",
];

/** `services.items.${it.i}.title` -> `services.items.N.title` */
const normalise = (p) =>
    p.replace(/\$\{[^}]*\}/g, "N")
     .replace(/\.\d+(?=\.|$)/g, ".N")
     .replace(/\.N\.N/g, ".N");

const PATH_RE = new RegExp(
    "\\b(" + ROOTS.join("|") + ")((?:\\.(?:\\$\\{[^}]*\\}|[A-Za-z0-9_]+))+)",
    "g",
);

const collectFrom = (file, acc) => {
    let src;
    try { src = fs.readFileSync(file, "utf8"); } catch { return; }
    for (const m of src.matchAll(PATH_RE)) acc.add(normalise(m[1] + m[2]));
    // A bare root is a hook too — data-field="navCtaText".
    for (const r of ROOTS) if (new RegExp('["\'`]' + r + '["\'`]').test(src)) acc.add(r);
};

/** Every .astro a wrapper pulls in, one or two levels deep. */
const importsOf = (file) => {
    let src;
    try { src = fs.readFileSync(file, "utf8"); } catch { return []; }
    const dir = path.dirname(file);
    const out = [];
    for (const m of src.matchAll(/from\s+['"](\.[^'"]*\.astro)['"]/g)) {
        const p = path.resolve(dir, m[1]);
        if (fs.existsSync(p)) out.push(p);
    }
    return out;
};

const walk = (file, acc, seen = new Set(), depth = 0) => {
    if (depth > 3 || seen.has(file)) return;
    seen.add(file);
    collectFrom(file, acc);
    for (const child of importsOf(file)) walk(child, acc, seen, depth + 1);
};

const manifest = {};
for (const fam of fs.readdirSync(COMPONENTS)) {
    const d = path.join(COMPONENTS, fam);
    if (!fs.statSync(d).isDirectory()) continue;
    for (const f of fs.readdirSync(d)) {
        const m = /^Page([A-Z]+)\.astro$/.exec(f);
        if (!m) continue;
        const acc = new Set();
        walk(path.join(d, f), acc);
        manifest[`${fam}:${m[1]}`] = [...acc].sort();
    }
}

const codes = Object.keys(manifest).sort();
const body = codes
    .map((c) => `    ${JSON.stringify(c)}: [\n${manifest[c].map((p) => `        ${JSON.stringify(p)},`).join("\n")}\n    ],`)
    .join("\n");

const file = `/* AUTO-GENERATED by scripts/gen-template-fields.mjs — DO NOT EDIT BY HAND.
 *
 * The content paths each template actually binds, read off its wrapper and the
 * section components it imports. The Content panel hides any field whose path
 * is not here, so it stops offering inputs that write to storage and change
 * nothing on the page. Regenerate after adding or removing a hook:
 *
 *   node scripts/gen-template-fields.mjs
 *
 * \`node scripts/gen-template-fields.mjs --check\` fails when this file is stale.
 *
 * List indexes are normalised to N: "services.items.N.title" covers every row.
 *
 * The scan FAILS OPEN — it matches path-shaped tokens anywhere in a file,
 * comments included — so a path mentioned but not bound keeps its input. A
 * spare field an admin can ignore beats a missing one they need.
 */
export const TEMPLATE_FIELD_PATHS: Record<string, string[]> = {
${body}
};
`;

// Only act when RUN. check-template-field-roots.mjs imports ROOTS from this
// module so the two share one list instead of two that drift, and an import
// must not rewrite a generated file as a side effect.
const RUN_AS_SCRIPT =
    process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (!RUN_AS_SCRIPT) {
    // imported for ROOTS only
} else if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    const norm = (s) => s.split("\r\n").join("\n");
    if (norm(current) !== norm(file)) {
        console.error(
            "✗ templateFieldPaths.generated.ts is STALE — a component's hooks changed.\n" +
            "  Run: node scripts/gen-template-fields.mjs"
        );
        process.exit(1);
    }
    console.log(`✓ template field paths OK — ${codes.length} templates, generated file matches the components`);
} else {
    fs.writeFileSync(OUT, file);
    const total = codes.reduce((n, c) => n + manifest[c].length, 0);
    console.log(`wrote ${path.relative(ROOT, OUT)} — ${codes.length} templates, ${total} bound paths`);
}
