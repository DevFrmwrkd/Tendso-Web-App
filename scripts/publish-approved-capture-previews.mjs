/** Compose approved and legacy examples without duplicating shared media bytes. */
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

const normalize = value => value.replace(/\r\n/g, '\n');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const mime = { '.webp':'image/webp', '.png':'image/png', '.jpg':'image/jpeg', '.jpeg':'image/jpeg', '.woff2':'font/woff2' };

export async function publishApprovedCapturePreviews(root, approved, { check = false } = {}) {
  const publicDir = path.join(root, 'public');
  const legacyDir = path.join(publicDir, 'capture-previews');
  const legacyCatalog = JSON.parse(await fs.readFile(path.join(legacyDir, 'catalog.json'), 'utf8'));
  const documents = {}, assets = {};
  const fontCss = normalize(await fs.readFile(path.join(legacyDir, 'fonts/native-fonts.css'), 'utf8'));
  const readHtml = async preview => {
    if (!/^\/(?:capture-previews|capture-redesign)\/[a-z0-9-]+\.html$/.test(preview)) throw new Error('Unsafe capture preview path');
    return normalize(await fs.readFile(path.join(publicDir, preview.slice(1)), 'utf8'));
  };
  for (const design of legacyCatalog.designs) documents[design.code] = await readHtml(design.preview);
  for (const design of approved.designs) {
    let html = await readHtml(design.preview);
    // Native previews retain the exact typefaces even with no network. Public
    // generated sites keep their standard hosted font stylesheet references.
    html = html.replace(/<link\b[^>]*href=["']https:\/\/fonts\.(?:googleapis|gstatic)\.com[^"']*["'][^>]*>/g, '');
    documents[design.code] = html.replace('</head>', `<style data-offline-business-fonts>${fontCss}</style></head>`);
  }
  const references = new Set(Object.values(documents).flatMap(html =>
    [...html.matchAll(/\/capture-previews\/(?:photos|fonts)\/[a-z0-9-]+\.(?:webp|jpe?g|png|woff2)/g)].map(match => match[0])));
  for (const url of [...references].sort()) {
    const bytes = await fs.readFile(path.join(publicDir, url.slice(1)));
    assets[url] = `data:${mime[path.extname(url)]};base64,${bytes.toString('base64')}`;
  }
  const sourceHash = hash(JSON.stringify({ approved:approved.sourceHash, legacy:legacyCatalog.sourceHash, documents, assets }));
  const native = `// Generated by scripts/build-capture-redesign.mjs. Do not edit.\n// Approved and saved legacy examples share one copy of every photo/font.\nexport const CAPTURE_PREVIEW_VERSION = 2;\nexport const CAPTURE_PREVIEW_SOURCE_HASH = ${JSON.stringify(sourceHash)};\nexport const CAPTURE_PREVIEW_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(assets)};\nexport const CAPTURE_PREVIEW_DOCUMENTS: Readonly<Record<string, string>> = ${JSON.stringify(documents)};\n`;
  const catalog = `// Generated by scripts/build-capture-redesign.mjs. Do not edit.\n// Metadata only: this import never loads document or image bytes.\nexport const CAPTURE_PREVIEW_CATALOG = ${JSON.stringify(approved.designs)} as const;\nexport const LEGACY_CAPTURE_PREVIEW_CATALOG = ${JSON.stringify(legacyCatalog.designs)} as const;\n`;
  const nativeFile = path.join(root, 'apps/mobile/generated/capturePreviews.ts');
  const catalogFile = path.join(root, 'apps/mobile/services/generated/capturePreviewCatalog.ts');
  if (check) {
    if (normalize(await fs.readFile(nativeFile, 'utf8')) !== native || normalize(await fs.readFile(catalogFile, 'utf8')) !== catalog)
      throw new Error('Approved native capture previews are stale. Rebuild scripts/build-capture-redesign.mjs.');
  } else {
    await fs.writeFile(nativeFile, native);
    await fs.writeFile(catalogFile, catalog);
    // The legacy builder checks these shared artifacts too. Keeping their exact
    // hashes current preserves its existing --check contract after composition.
    const legacyManifestPath = path.join(legacyDir, 'manifest.json');
    const legacyManifest = JSON.parse(await fs.readFile(legacyManifestPath, 'utf8'));
    legacyManifest.nativeSha256 = hash(native);
    legacyManifest.nativeCatalogSha256 = hash(catalog);
    await fs.writeFile(legacyManifestPath, JSON.stringify(legacyManifest, null, 2) + '\n');
  }
  return { sourceHash, documents:Object.keys(documents).length, photos:[...references].filter(url=>url.includes('/photos/')).length,
    fonts:[...references].filter(url=>url.includes('/fonts/')).length, nativeSha256:hash(native), nativeCatalogSha256:hash(catalog) };
}
