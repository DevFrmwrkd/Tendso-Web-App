#!/usr/bin/env node
/**
 * Turn a legacy per-business Cloudflare Worker into a 301 redirect to that
 * site's <slug>.sites.tendso.com address.
 *
 * WHY THIS EXISTS. Publishing used to deploy one Worker per business and report
 * its workers.dev URL to the owner. Sites are now served by
 * app/hosted/[slug]/route.ts and publishing mints no Worker, but the old ones are
 * still live and still serving a full copy of the page — with no canonical tag,
 * because the canonical is injected by the hosted route and those bytes were
 * stored long before it existed. So the same page sits at two addresses and only
 * one of them says which is the original.
 *
 * Deleting them would answer that, and break every link already emailed to an
 * owner or printed on their signage. A 301 keeps those links working AND hands
 * the ranking signal to the address we want indexed, which is the whole point.
 *
 * REFUSES A WORKER WITH A CUSTOM DOMAIN ATTACHED. Cloudflare serves a paid domain
 * from this same script, so replacing it with a redirect would send
 * benjoetiresupply.com to a tendso.com subdomain — backwards, and it would take a
 * paying customer's site down. The check is not optional and there is no flag to
 * skip it.
 *
 * Usage (dry run prints exactly what it would do and changes nothing):
 *
 *   node scripts/redirect-legacy-workers.mjs \
 *       --pair deluxia-coffee=deluxia-coffee \
 *       --pair neighborhood=neighborhood
 *
 *   node scripts/redirect-legacy-workers.mjs --pair <worker>=<slug> --apply
 *
 * Each pair is <worker script name>=<site slug>. Both are stated explicitly
 * rather than derived: the Worker name comes from `cfPagesProjectName` and the
 * slug from `slug`, and they are NOT always the same string (slugs fold accents
 * and resolve collisions with a -2 suffix, Worker names do not).
 *
 * Credentials come from CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID, read from
 * the environment or from .env.local.
 */
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SITES_SUFFIX = '.sites.tendso.com'
const CF = 'https://api.cloudflare.com/client/v4'

/** Read a key from .env.local without pulling in a dotenv dependency. */
function fromEnvLocal(key) {
    try {
        const raw = readFileSync(resolve(process.cwd(), '.env.local'), 'utf-8')
        const line = raw.split(/\r?\n/).find((l) => l.startsWith(`${key}=`))
        return line ? line.slice(key.length + 1).trim().replace(/^["']|["']$/g, '') : undefined
    } catch {
        return undefined
    }
}

/**
 * Accepts `--pair a=b`, `--pair=a=b` and a bare `a=b`.
 *
 * Indexed rather than a for..of because `--pair a=b` arrives as TWO argv entries
 * and the flag has to be able to consume the one after it.
 */
export function parseArgs(argv) {
    const pairs = []
    let apply = false

    const push = (value, source) => {
        const [worker, slug] = String(value).split('=')
        if (!worker || !slug) {
            throw new Error(`Expected <worker>=<slug>, got: ${source}`)
        }
        pairs.push({ worker, slug })
    }

    for (let i = 0; i < argv.length; i++) {
        const arg = argv[i]
        if (arg === '--apply') { apply = true; continue }
        if (arg === '--pair') {
            const next = argv[++i]
            if (next === undefined) throw new Error('--pair needs a <worker>=<slug> after it')
            push(next, `--pair ${next}`)
            continue
        }
        if (arg.startsWith('--pair=')) { push(arg.slice('--pair='.length), arg); continue }
        if (!arg.startsWith('--')) { push(arg, arg); continue }
        throw new Error(`Unrecognised argument: ${arg}`)
    }
    return { pairs, apply }
}

async function cf(token, path, init = {}) {
    const res = await fetch(`${CF}${path}`, {
        ...init,
        headers: { Authorization: `Bearer ${token}`, ...(init.headers || {}) },
    })
    const body = await res.json().catch(() => ({}))
    if (!res.ok) {
        const msg = body?.errors?.map((e) => e.message).join(', ') || `HTTP ${res.status}`
        throw new Error(msg)
    }
    return body.result
}

/**
 * Every custom hostname Cloudflare serves from this script.
 *
 * The guard that keeps a paying customer's domain from being redirected at its
 * own site. A lookup failure is treated as "cannot prove it is safe" and the
 * Worker is skipped — never assumed clear.
 */
async function customDomainsFor(token, accountId, workerName) {
    const domains = await cf(token, `/accounts/${accountId}/workers/domains`)
    return (domains || [])
        .filter((d) => d.service === workerName)
        .map((d) => d.hostname)
}

/** The redirect Worker. Every path on the old host goes to the new site root. */
export function redirectScript(target) {
    return `// Generated by scripts/redirect-legacy-workers.mjs.
// This business's site is served from ${target} now. Everything here is a
// permanent redirect so links already emailed or printed keep working, and so
// the ranking signal for the duplicate copy transfers to the real address.
export default {
  async fetch() {
    return Response.redirect(${JSON.stringify(target)}, 301);
  },
};
`
}

async function putWorker(token, accountId, workerName, script) {
    const boundary = `----RedirectDeploy${Date.now()}`
    const metadata = JSON.stringify({ main_module: 'worker.js', compatibility_date: '2024-01-01' })
    const body = Buffer.concat([
        Buffer.from(
            `--${boundary}\r\n` +
            `Content-Disposition: form-data; name="metadata"; filename="metadata.json"\r\n` +
            `Content-Type: application/json\r\n\r\n${metadata}\r\n`,
        ),
        Buffer.from(
            `--${boundary}\r\n` +
            `Content-Disposition: form-data; name="worker.js"; filename="worker.js"\r\n` +
            `Content-Type: application/javascript+module\r\n\r\n`,
        ),
        Buffer.from(script, 'utf-8'),
        Buffer.from(`\r\n--${boundary}--\r\n`),
    ])
    await cf(token, `/accounts/${accountId}/workers/scripts/${workerName}`, {
        method: 'PUT',
        headers: { 'Content-Type': `multipart/form-data; boundary=${boundary}` },
        body,
    })
}

async function main() {
    const { pairs, apply } = parseArgs(process.argv.slice(2))
    if (!pairs.length) {
        console.error('Nothing to do. Pass at least one --pair <worker>=<slug>. See the header of this file.')
        process.exit(1)
    }

    const token = process.env.CLOUDFLARE_API_TOKEN || fromEnvLocal('CLOUDFLARE_API_TOKEN')
    const accountId = process.env.CLOUDFLARE_ACCOUNT_ID || fromEnvLocal('CLOUDFLARE_ACCOUNT_ID')
    if (!token || !accountId) {
        console.error('Missing CLOUDFLARE_API_TOKEN / CLOUDFLARE_ACCOUNT_ID (environment or .env.local).')
        process.exit(1)
    }

    console.log(apply
        ? '── APPLYING. Each Worker below is replaced with a 301.\n'
        : '── DRY RUN. Nothing is changed. Re-run with --apply to write.\n')

    let done = 0
    let skipped = 0
    for (const { worker, slug } of pairs) {
        const target = `https://${slug}${SITES_SUFFIX}/`
        let attached
        try {
            attached = await customDomainsFor(token, accountId, worker)
        } catch (err) {
            console.log(`SKIP  ${worker} — could not list its custom domains (${err.message}). Not touching a Worker we cannot prove is safe.`)
            skipped++
            continue
        }

        if (attached.length) {
            console.log(`SKIP  ${worker} — serves ${attached.join(', ')}. A redirect here would take that domain down.`)
            skipped++
            continue
        }

        if (!apply) {
            console.log(`WOULD ${worker} → 301 ${target}`)
            done++
            continue
        }

        try {
            await putWorker(token, accountId, worker, redirectScript(target))
            console.log(`OK    ${worker} → 301 ${target}`)
            done++
        } catch (err) {
            console.log(`FAIL  ${worker} — ${err.message}`)
            skipped++
        }
    }

    console.log(`\n${apply ? 'Redirected' : 'Would redirect'}: ${done}. Skipped: ${skipped}.`)
    if (apply && done) {
        console.log('Verify with: curl -sI https://<worker>.<subdomain>.workers.dev/ | head -3')
    }
    // A skip is a decision the operator needs to see, not a failure of the run.
    process.exit(0)
}

// Only run when invoked as a script. Importing this file (a test, a REPL check)
// must not fire real Cloudflare writes — a guard script in this repo once ran its
// own generator on import and rewrote a tracked file as a side effect.
if (process.argv[1] && process.argv[1].endsWith('redirect-legacy-workers.mjs')) {
    main().catch((err) => {
        console.error(err.message || err)
        process.exit(1)
    })
}
